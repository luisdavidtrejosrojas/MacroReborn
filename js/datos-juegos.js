// ==============================
// IMAGEN DE JUEGO (helper compartido)
// ==============================
// Todas las secciones que muestran la portada de un juego (catálogo,
// destacados, favoritos, últimos jugados y ficha del juego) llaman a
// esta misma función en vez de escribir el <img> a mano en cada archivo.
// Así, la ruta de la imagen sale siempre de juego.imagen (datos-juegos.js)
// y queda en un solo lugar.

function crearImagenJuego(juego, opciones = {}){

    const lazy = opciones.lazy !== false;

    if(!juego || !juego.imagen){
        return `<div class="placeholder-juego"><span>🎮</span></div>`;
    }

    // loading="lazy" en catálogo/listas (fuera del viewport inicial) y
    // carga inmediata + prioridad alta en la ficha del juego (juego.html),
    // donde la imagen SÍ es lo primero que se ve (mejor LCP).
    const atributoCarga = lazy
        ? `loading="lazy"`
        : `loading="eager" fetchpriority="high"`;

    return `<img src="${juego.imagen}" alt="Portada del juego ${juego.nombre} en MacroReborn" ${atributoCarga} onerror="mostrarPlaceholderJuego(this)">`;

}

// Si la imagen no existe o no carga, la reemplazamos por un placeholder
// prolijo (sin romper el layout de la tarjeta) y avisamos por consola
// para poder detectar fácilmente qué juego se quedó sin portada.
function mostrarPlaceholderJuego(img){

    const contenedor = img.parentElement;

    console.warn("No se pudo cargar la imagen del juego:", img.src);

    img.remove();

    if(!contenedor) return;

    const marcador = document.createElement("div");
    marcador.className = "placeholder-juego";
    marcador.innerHTML = "<span>🎮</span>";

    contenedor.appendChild(marcador);

}